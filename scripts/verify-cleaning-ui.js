const { app, BrowserWindow } = require('electron');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const assert = require('node:assert/strict');
const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'gravesite-ui-'));
app.setPath('userData', path.join(directory, 'browser'));
Object.assign(process.env, { DATABASE_PATH: path.join(directory, 'test.sqlite'), UPLOADS_PATH: path.join(directory, 'uploads'), GRAVESITE_CONFIG_FOLDER: directory, GRAVESITE_ENV_PATH: path.join(directory, '.env'), APP_ACCESS_TOKEN: '', HOST: '127.0.0.1' });
let running, db, window;
app.whenReady().then(async () => {
  const { startServer } = require('../src/server');
  db = require('../src/db');
  const cleaning = require('../src/db/cleaning');
  const sharp = require('sharp');
  db.prepare("INSERT INTO cemeteries (cemetery_id, cemetery_name, cemetery_url) VALUES ('1', 'Maple Grove Cemetery', 'https://example.com')").run();
  db.prepare("INSERT INTO memorials (memorial_id, cemetery_id, full_name, raw_payload) VALUES (1, '1', 'Eleanor Whitmore', '{}')").run();
  const first = cleaning.saveSession(1, { visitDate: '2026-10-18', methods: 'D/2 and soft brush', notes: 'First cleaning. Photographed all sides before starting.' });
  const second = cleaning.saveSession(1, { visitDate: '2026-11-01', methods: 'Water and soft brush', notes: 'Second cleaning and condition review.' });
  await fs.promises.mkdir(process.env.UPLOADS_PATH, { recursive: true });
  for (const [index, date, stage, caption] of [[1,'2026-11-21','during','One-month follow-up — front view'], [2,'2026-11-21','during','One-month follow-up — side view'], [3,'2026-10-18','before','Before cleaning'], [4,'2026-11-21','after','Different cleaning, same photo date']]) {
    const name = `sample-${index}.jpg`;
    await sharp({ create: { width: 360, height: 260, channels: 3, background: index === 3 ? '#807d70' : '#b8bbad' } }).jpeg().toFile(path.join(process.env.UPLOADS_PATH, name));
    fs.copyFileSync(path.join(process.env.UPLOADS_PATH,name),path.join(process.env.UPLOADS_PATH,`thumb-${name}`));
    cleaning.addPhoto(index === 4 ? second.session_id : first.session_id, name, stage, caption, date);
  }
  running = await startServer(0);
  window = new BrowserWindow({ show: false, width: 1200, height: 1000, webPreferences: { contextIsolation: true, nodeIntegration: false } });
  await window.loadURL(`${running.url}/memorials/1`);
  const evaluate = code => window.webContents.executeJavaScript(code, true);
  assert.equal(await evaluate('document.querySelectorAll(".cleaning-dialog[open]").length'), 0);
  assert.equal(await evaluate('document.querySelector(".timeline-update time").textContent'), '2026-11-21');
  assert.equal(await evaluate('document.querySelectorAll(".timeline-session[open]").length'), 0);
  assert.equal(await evaluate(`document.querySelector('#session-${first.session_id}').querySelectorAll('.timeline-photo-card').length`), 3);
  assert.equal(await evaluate(`document.querySelector('#session-${second.session_id}').querySelectorAll('.timeline-photo-card').length`), 1);
  await evaluate(`document.querySelector('#session-${first.session_id} > summary').click()`);
  assert.equal(await evaluate(`document.querySelector('#session-${first.session_id}').open`), true);
  assert.equal(await evaluate(`document.querySelector('#session-${second.session_id}').open`), false);
  await evaluate(`document.querySelector('#session-${first.session_id} .timeline-update > summary').click()`);
  assert.equal(await evaluate(`document.querySelector('#session-${first.session_id} .timeline-update').open`), true);
  await evaluate('document.querySelector("[data-open-dialog=new-session-dialog]").click()');
  assert.equal(await evaluate('document.querySelector("#new-session-dialog").open'), true);
  assert.equal(await evaluate('document.querySelectorAll(".cleaning-dialog[open]").length'), 1);
  fs.writeFileSync('/private/tmp/gravescraper-new-session-desktop.png', (await window.webContents.capturePage()).toPNG());
  await evaluate('document.querySelector("#new-session-dialog [data-close-dialog]").click()');
  await evaluate(`document.querySelector('[data-open-dialog="edit-session-${first.session_id}"]').click()`);
  assert.equal(await evaluate(`document.querySelector('#edit-session-${first.session_id} [name=methods]').value`), 'D/2 and soft brush');
  await evaluate(`document.querySelector('#edit-session-${first.session_id} [data-close-dialog]').click()`);
  await evaluate(`document.querySelector('[data-open-dialog="upload-photos-dialog"][data-session-id="${first.session_id}"]').click()`);
  assert.equal(await evaluate('document.querySelector("#uploadSession").value'), String(first.session_id));
  assert.equal(await evaluate('document.querySelector("#progressStage").value'), 'before');
  await evaluate(`document.querySelector('#uploadSession').value='${second.session_id}'; document.querySelector('#uploadSession').dispatchEvent(new Event('change'))`);
  assert.match(await evaluate('document.querySelector(".photo-upload-form").action'), new RegExp(`/cleaning-sessions/${second.session_id}/photos$`));
  await evaluate('document.querySelector("#upload-photos-dialog [data-close-dialog]").click()');
  await evaluate('window.scrollTo(0,0)');
  await new Promise(resolve => setTimeout(resolve, 100));
  fs.writeFileSync('/private/tmp/gravescraper-timeline-desktop.png', (await window.webContents.capturePage()).toPNG());
  await window.loadURL(`${running.url}/memorials/1?addPhotos=${first.session_id}`);
  assert.equal(await evaluate('document.querySelector("#upload-photos-dialog").open'), true);
  assert.equal(await evaluate('document.querySelector("#progressStage").value'), 'before');
  assert.ok(!(await evaluate('location.search')).includes('addPhotos'));
  window.setSize(390, 844);
  await evaluate('document.querySelector("#upload-photos-dialog").close(); document.querySelector("[data-open-dialog=new-session-dialog]").click()');
  await new Promise(resolve => setTimeout(resolve, 150));
  assert.equal(await evaluate('document.documentElement.scrollWidth <= innerWidth'), true);
  assert.equal(await evaluate('document.querySelector("#new-session-dialog").getBoundingClientRect().width <= innerWidth'), true);
  fs.writeFileSync('/private/tmp/gravescraper-new-session-mobile.png', (await window.webContents.capturePage()).toPNG());
  const navigation = new Promise(resolve => window.webContents.once('did-finish-load', resolve));
  await evaluate(`document.querySelector('#visitDate').value='2026-11-22'; document.querySelector('#sessionMethods').value='New visit'; document.querySelector('#new-session-dialog form').requestSubmit(document.querySelector('#new-session-dialog [name=next]'))`);
  await navigation;
  assert.equal(await evaluate('document.querySelector("#upload-photos-dialog").open'), true);
  const newest = cleaning.listSessions(1)[0];
  assert.equal(newest.visit_date, '2026-11-22');
  assert.equal(await evaluate('document.querySelector("#uploadSession").value'), String(newest.session_id));
  await window.loadURL(`${running.url}/memorials/1#photo-3`);
  assert.equal(await evaluate(`document.querySelector('#session-${first.session_id}').open`), true);
  assert.equal(await evaluate('document.querySelector("#photo-3").closest(".timeline-update").open'), true);
  await evaluate('document.querySelector("#upload-photos-dialog [data-close-dialog]").click()');
  await evaluate(`document.querySelector('[data-open-dialog="delete-session-${first.session_id}"]').click()`);
  assert.equal(await evaluate(`document.querySelector('#delete-session-${first.session_id}').open`), true);
  assert.match(await evaluate(`document.querySelector('#delete-session-${first.session_id}').textContent`), /3 attached photo/);
  await evaluate(`document.querySelector('#delete-session-${first.session_id} [data-close-dialog]').click()`);
  assert.ok(cleaning.getSession(first.session_id));
  await evaluate('document.querySelector("[data-open-dialog=edit-photo-1]").click()');
  await evaluate('document.querySelector("#edit-photo-1 [data-open-dialog=delete-photo-1]").click()');
  assert.equal(await evaluate('document.querySelector("#delete-photo-1").open'), true);
  await evaluate('document.querySelector("#delete-photo-1 [data-close-dialog]").click()');
  assert.ok(cleaning.getPhotoFile(1));
  await window.loadURL(`${running.url}/?activeSearch=Eleanor`);
  assert.equal(await evaluate('document.querySelectorAll(".active-grave-card").length'), 1);
  assert.match(await evaluate('document.querySelector(".active-grave-card").textContent'), /Maple Grove/);
  assert.equal(await evaluate('document.documentElement.scrollWidth <= innerWidth'), true);
  console.log('Cleaning UI verified: timeline ordering, separate modal flows, session selection, upload handoff, and mobile layout.');
}).catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => {
  if (window) window.destroy();
  if (running) await new Promise(resolve => running.server.close(resolve));
  if (db) db.close();
  fs.rmSync(directory, { recursive: true, force: true });
  app.exit(process.exitCode || 0);
});

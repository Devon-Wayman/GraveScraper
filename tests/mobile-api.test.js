const { test } = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");

test("authenticated mobile API, cleaning history, uploads, and import preservation", async () => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), "gravesite-mobile-"));
  process.env.DATABASE_PATH = path.join(directory, "test.sqlite");
  process.env.UPLOADS_PATH = path.join(directory, "photos");
  process.env.APP_ACCESS_TOKEN = "test-secret-with-at-least-24-characters";
  const { app } = require("../src/server");
  const db = require("../src/db");
  const repositories = require("../src/db/repositories");
  const sharp = require("sharp");
  db.prepare("INSERT INTO cemeteries (cemetery_id, cemetery_name, cemetery_url) VALUES ('1', 'Test Cemetery', 'https://example.com')").run();
  db.prepare("INSERT INTO memorials (memorial_id, cemetery_id, full_name, raw_payload) VALUES (10, '1', 'Test Person', '{}')").run();
  const server = app.listen(0, "127.0.0.1");
  await new Promise((resolve, reject) => { server.once("listening", resolve); server.once("error", reject); });
  const base = `http://127.0.0.1:${server.address().port}`;
  const headers = { Authorization: `Bearer ${process.env.APP_ACCESS_TOKEN}` };
  const request = (url, init = {}) => fetch(base + url, { ...init, headers: { ...headers, ...init.headers } });
  const json = (method, body) => ({ method, headers: { "Content-Type": "application/json" }, body: JSON.stringify(body) });
  const upload = (session, bytes, stage = "before", photoDate = "2026-10-20") => {
    const form = new FormData();
    form.set("stage", stage); form.set("caption", "Stone progress");
    form.set("photoDate", photoDate);
    form.set("photo", new Blob([bytes], { type: "image/png" }), "photo.png");
    return request(`/api/v1/cleaning-sessions/${session}/photos`, { method: "POST", body: form });
  };
  try {
    assert.equal((await fetch(base + "/")).status, 401);
    assert.equal((await fetch(base + "/styles.css")).status, 401);
    const basic = Buffer.from(`gravescraper:${process.env.APP_ACCESS_TOKEN}`).toString("base64");
    assert.equal((await fetch(base + "/", { headers: { Authorization: `Basic ${basic}` } })).status, 200);
    assert.equal((await request("/api/v1/cemeteries/1", { ...json("PATCH", { ownerName: "City" }), headers: { ...json("PATCH", {}).headers, Origin: "https://foreign.example" } })).status, 403);
    let response = await request("/api/v1/cemeteries/1", json("PATCH", { ownerName: "City", permissionStatus: "granted" }));
    assert.equal(response.status, 200);
    assert.equal((await response.json()).cemetery.owner_name, "City");
    assert.equal((await request("/api/v1/cemeteries/1", json("PATCH", { permissionStatus: "nonsense" }))).status, 400);
    response = await request("/api/v1/cemeteries/1", { method: "PATCH", headers: { "Content-Type": "application/json" }, body: "{broken" });
    assert.equal(response.status, 400);
    assert.ok((await response.json()).error);
    response = await request("/api/v1/memorials/10", json("PATCH", { userNotes: "Local notes", visitPriority: "high" }));
    assert.equal(response.status, 200);
    response = await request("/api/v1/memorials/10", json("PATCH", { userNotes: "Updated" }));
    assert.equal((await response.json()).memorial.visit_priority, "high");
    assert.equal((await request("/api/v1/cemeteries/1/memorials?page=0")).status, 400);
    assert.equal((await request("/api/v1/memorials/10/cleaning-sessions", json("POST", { visitDate: "2026-02-30" }))).status, 400);
    response = await request("/api/v1/memorials/10/cleaning-sessions", json("POST", { visitDate: "2026-10-20", methods: "Water", notes: "<script>test</script>" }));
    assert.equal(response.status, 201);
    const session = (await response.json()).session.session_id;
    response = await request(`/api/v1/cleaning-sessions/${session}`, json("PATCH", { methods: "Soft brush" }));
    assert.equal((await response.json()).session.visit_date, "2026-10-20");
    const image = await sharp({ create: { width: 30, height: 20, channels: 3, background: "green" } }).png().toBuffer();
    response = await upload(session, image);
    assert.equal(response.status, 201);
    const photo = (await response.json()).photo;
    assert.equal(photo.stage, "before");
    assert.ok(!photo.filename);
    assert.equal((await fetch(base + photo.url)).status, 401);
    response = await request(photo.url);
    assert.equal(response.headers.get("content-type"), "image/jpeg");
    assert.equal((await sharp(Buffer.from(await response.arrayBuffer())).metadata()).format, "jpeg");
    assert.equal((await request(photo.thumbnail_url)).status, 200);
    response = await request(`/api/v1/photos/${photo.photo_id}`, json("PATCH", { caption: "Initial condition" }));
    assert.equal((await response.json()).photo.caption, "Initial condition");
    assert.equal(photo.photo_date, "2026-10-20");
    assert.equal((await upload(session, image, "after", "2026-12-20")).status, 201);
    assert.equal((await upload(session, image, "during", "2026-11-01")).status, 201);
    assert.equal((await upload(session, image, "during", "2026-11-15")).status, 201);
    const timeline = (await (await request(`/api/v1/cleaning-sessions/${session}`)).json()).session.photos;
    assert.deepEqual(timeline.map(p => p.photo_date), ["2026-10-20", "2026-11-01", "2026-11-15", "2026-12-20"]);
    const savedFiles = fs.readdirSync(process.env.UPLOADS_PATH).length;
    assert.equal(savedFiles, 8);
    assert.equal((await upload(session, Buffer.from("not an image"))).status, 400);
    assert.equal((await upload(session, image, "invalid")).status, 400);
    assert.equal((await upload(session, image, "during", "2026-02-30")).status, 400);
    assert.equal((await upload(99999, image)).status, 404);
    assert.equal((await upload(session, Buffer.alloc(21 * 1024 * 1024))).status, 413);
    assert.equal(fs.readdirSync(process.env.UPLOADS_PATH).length, savedFiles);
    const html = await (await request("/memorials/10")).text();
    assert.match(html, /Cleaning history/);
    assert.match(html, /&lt;script&gt;test&lt;\/script&gt;/);
    assert.match(html, /Soft brush/);
    assert.match(html, /2026-11-15/);
    const formPost = (url, body) => request(url, { method: "POST", body: new URLSearchParams(body), redirect: "manual" });
    response = await formPost(`/cleaning-sessions/${session}`, { visitDate: "2026-10-20", methods: "Water and soft brush", notes: "Browser edit" });
    assert.equal(response.status, 302);
    response = await formPost(`/photos/${photo.photo_id}`, { photoDate: "2026-10-20", stage: "before", caption: "Browser caption" });
    assert.equal(response.status, 302);
    response = await formPost("/memorials/10/cleaning-sessions", { visitDate: "invalid" });
    assert.equal(response.status, 400);
    assert.match(await response.text(), /Enter a valid visit date/);
    response = await formPost("/memorials/10/cleaning-sessions", { visitDate: "2027-01-20", notes: "New cleaning" });
    assert.equal(response.status, 302);
    assert.match(response.headers.get("location"), /#session-/);
    assert.equal((await request("/api/v1/missing")).status, 404);
    repositories.syncMemorialsForCemetery("1", []);
    assert.ok(repositories.getMemorialById(10));
    assert.equal((await (await request(`/api/v1/cleaning-sessions/${session}`)).json()).session.photos.length, 4);
    repositories.deleteCemeteryById("1");
    assert.equal(fs.readdirSync(process.env.UPLOADS_PATH).length, 0);
    assert.equal((await request(photo.url)).status, 404);
  } finally {
    await new Promise(resolve => server.close(resolve));
    db.close();
    fs.rmSync(directory, { recursive: true, force: true });
  }
});
